################################################################################
#
# This is a short helper script for embedding the TrACE HTML template into the
# data preparation script, and then compressing all necessary files into a 
# standalone .pyz file.
#
# Anton Malko, 2026
################################################################################

import base64
import shutil
import tempfile
import zlib
from pathlib import Path
from zipapp import create_archive

# Paths ----
this_script_path = Path(__file__).resolve()
main_dir = this_script_path.parent.parent
app_dir = main_dir.joinpath("make_trace")
template_path = main_dir.joinpath("TrACE_template.html")
target_path = main_dir.joinpath("make_trace.pyz")

# The temporary folder and everything in it are deleted automatically when
# the `with` block ends, also if building fails
with tempfile.TemporaryDirectory() as tmp:
    # Copy the app, so that the source files are never changed ----
    staging_dir = Path(tmp).joinpath("make_trace")
    shutil.copytree(app_dir, staging_dir,
                    ignore=shutil.ignore_patterns("__pycache__"))

    # Embed HTML template into the copy ----
    # Compress and encode to ASCII text
    compressed = zlib.compress(template_path.read_bytes())
    encoded = base64.b64encode(compressed).decode("ascii")
    staging_dir.joinpath("template_data.py").write_text(
        "# Generated by build/package.py from TrACE_template.html\n"
        f'TRACE_TEMPLATE = "{encoded}"\n',
        encoding="utf-8")

    # Package the app ----
    create_archive(source=staging_dir, target=target_path, compressed=True)

print(f"Built {target_path}")
